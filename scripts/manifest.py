"""
Manifest library for TaxonBodyMassML model artifacts.

A *manifest* is a dict that describes every published model version and every
provenance snapshot.  It is the single source of truth for:

  - which files belong to each (method, version) pair, with SHA-256 + size
  - which package version first shipped that model (``package_min``)
  - training metrics and database version for each model version
  - which provenance snapshots exist and their checksums

The canonical copy lives in the two packages:
  packages/python/taxonbodymassml/data/manifest.json
  packages/r/inst/extdata/manifest.json

``artifacts/manifest.json`` is a build-time output regenerated by
``scripts/export_artifacts.py`` and then synced into the packages by
``scripts/sync_manifest.py``.

Schema (schema_version 1)
--------------------------
{
  "schema_version": 1,
  "release": <int>,           # bumped on each publish_artifacts.py run
  "hub_repo": "marknovak/TaxonBodyMassML",
  "models": {
    "<Method>": {
      "v<n>": {
        "path":        "models/<Method>/v<n>",
        "db_version":  "<tag>",
        "trained":     "<ISO-8601 UTC>",
        "package_min": "<semver>",
        "files": {
          "<name>": {"sha256": "<hex>", "size": <bytes>}
        },
        "metrics": {"r2": <float>, "rmse": <float>, "mae": <float>,
                    "n_train": <int>, "n_test": <int>},
        "notes": "<free text>"
      }
    }
  },
  "provenance": {
    "<db_version>": {
      "path":  "provenance/<db_version>",
      "files": {"<name>": {"sha256": "<hex>", "size": <bytes>}}
    }
  }
}

Public API
----------
  load(path)                       -> dict
  save(manifest, path)
  newest(manifest, method)         -> int | None
  cached_versions(manifest, method, cache_dir) -> list[int]
  add_model(manifest, method, version, folder, meta)
  add_provenance(manifest, db_version, folder)
  validate(manifest)               -> None  (raises ValueError on problems)
  render_model_card(manifest)      -> str
  sha256_file(path)                -> str
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any

# ---------------------------------------------------------------------------
# Schema constant
# ---------------------------------------------------------------------------

SCHEMA_VERSION = 1
HUB_REPO = "marknovak/TaxonBodyMassML"

# Files that belong to every model version (in addition to method-specific ones)
COMMON_MODEL_FILES = {
    "model.ubj",
    "calibration.json",
    "calibration_by_rank.json",
    "categories.json",
    "lookup.json",
}
EE_ONLY_FILES = {"embeddings.json"}

# Methods and their expected file sets (normalized names, no _ee suffix)
METHOD_FILES: dict[str, set[str]] = {
    "XGBoost": COMMON_MODEL_FILES,
    "EntityEmbeddings": COMMON_MODEL_FILES | EE_ONLY_FILES,
}

PROVENANCE_FILES = {"PrimaryCitations_BodyMass.bib", "TaxonBodyMass_Provenance.csv.gz"}


# ---------------------------------------------------------------------------
# I/O
# ---------------------------------------------------------------------------


def load(path: str | Path) -> dict[str, Any]:
    """Load a manifest JSON file and return it as a dict."""
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def save(manifest: dict[str, Any], path: str | Path) -> None:
    """Save *manifest* to *path* as pretty-printed JSON."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def empty() -> dict[str, Any]:
    """Return a new empty manifest with schema defaults."""
    return {
        "schema_version": SCHEMA_VERSION,
        "release": 0,
        "hub_repo": HUB_REPO,
        "models": {},
        "provenance": {},
    }


# ---------------------------------------------------------------------------
# Version resolution
# ---------------------------------------------------------------------------


def _version_keys(manifest: dict, method: str) -> list[int]:
    """Sorted list of integer version numbers for *method* (may be empty)."""
    versions = manifest.get("models", {}).get(method, {})
    result = []
    for k in versions:
        m = re.fullmatch(r"v(\d+)", k)
        if m:
            result.append(int(m.group(1)))
    return sorted(result)


def newest(manifest: dict, method: str) -> int | None:
    """Return the highest version number for *method*, or None if absent."""
    keys = _version_keys(manifest, method)
    return keys[-1] if keys else None


def cached_versions(manifest: dict, method: str, cache_dir: Path) -> list[int]:
    """Return sorted list of version numbers for *method* that are locally cached
    and whose files all pass SHA-256 verification."""
    result = []
    for v in _version_keys(manifest, method):
        key = f"v{v}"
        entry = manifest["models"][method][key]
        folder = cache_dir / entry["path"]
        if _all_files_ok(folder, entry["files"]):
            result.append(v)
    return result


def _all_files_ok(folder: Path, files: dict[str, dict]) -> bool:
    for name, info in files.items():
        p = folder / name
        if not p.exists():
            return False
        if sha256_file(p) != info["sha256"]:
            return False
    return True


# ---------------------------------------------------------------------------
# Mutation
# ---------------------------------------------------------------------------


def add_model(
    manifest: dict[str, Any],
    method: str,
    version: int,
    folder: Path,
    *,
    db_version: str,
    trained: str,
    package_min: str,
    metrics: dict[str, Any],
    notes: str = "",
) -> None:
    """Add or update a model entry in *manifest* (mutates in place).

    *folder* must be the directory containing the model files for this version.
    File names, SHA-256 hashes and sizes are read from disk.

    Raises ``FileNotFoundError`` if an expected file is missing from *folder*.
    Raises ``ValueError`` if the method is unknown or the version already exists
    and the files differ (use a new version number instead).
    """
    if method not in METHOD_FILES:
        raise ValueError(f"Unknown method {method!r}. Known: {sorted(METHOD_FILES)}")

    expected = METHOD_FILES[method]
    files_meta: dict[str, dict] = {}
    for name in sorted(expected):
        p = folder / name
        if not p.exists():
            raise FileNotFoundError(f"Expected file missing: {p}")
        files_meta[name] = {"sha256": sha256_file(p), "size": p.stat().st_size}

    path_str = f"models/{method}/v{version}"
    key = f"v{version}"

    manifest.setdefault("models", {}).setdefault(method, {})
    if key in manifest["models"][method]:
        existing = manifest["models"][method][key]
        if existing["files"] != files_meta:
            raise ValueError(
                f"{method} v{version} already exists in the manifest with different files. "
                "Increment the version number instead of overwriting."
            )
        # Same files — idempotent, just update mutable metadata
        manifest["models"][method][key].update(
            db_version=db_version,
            trained=trained,
            package_min=package_min,
            metrics=metrics,
            notes=notes,
        )
        return

    manifest["models"][method][key] = {
        "path": path_str,
        "db_version": db_version,
        "trained": trained,
        "package_min": package_min,
        "files": files_meta,
        "metrics": metrics,
        "notes": notes,
    }


def add_provenance(
    manifest: dict[str, Any],
    db_version: str,
    folder: Path,
) -> None:
    """Add or update a provenance entry for *db_version* (mutates in place).

    *folder* must contain ``PrimaryCitations_BodyMass.bib`` and
    ``TaxonBodyMass_Provenance.csv.gz``.
    """
    files_meta: dict[str, dict] = {}
    for name in sorted(PROVENANCE_FILES):
        p = folder / name
        if not p.exists():
            raise FileNotFoundError(f"Expected provenance file missing: {p}")
        files_meta[name] = {"sha256": sha256_file(p), "size": p.stat().st_size}

    manifest.setdefault("provenance", {})[db_version] = {
        "path": f"provenance/{db_version}",
        "files": files_meta,
    }


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------


def validate(manifest: dict[str, Any]) -> None:
    """Raise ``ValueError`` describing every structural problem found.

    Checks: schema_version present; release is a positive int; every model
    entry has the required keys and its path matches the method/version; file
    entries have sha256 + size; version numbers are contiguous from 1; known
    methods only; provenance entries have the right files.
    """
    errors: list[str] = []

    if manifest.get("schema_version") != SCHEMA_VERSION:
        errors.append(f"schema_version must be {SCHEMA_VERSION}")
    if not isinstance(manifest.get("release"), int) or manifest.get("release", 0) < 0:
        errors.append("release must be a non-negative integer")

    for method, versions in manifest.get("models", {}).items():
        if method not in METHOD_FILES:
            errors.append(f"Unknown method {method!r}")
            continue
        nums = sorted(int(m.group(1)) for k in versions if (m := re.fullmatch(r"v(\d+)", k)))
        if nums and nums != list(range(1, nums[-1] + 1)):
            errors.append(f"{method}: version numbers must be contiguous from 1, got {nums}")

        for key, entry in versions.items():
            if not re.fullmatch(r"v\d+", key):
                errors.append(f"{method}: invalid version key {key!r}")
                continue
            n = int(key[1:])
            expected_path = f"models/{method}/v{n}"
            if entry.get("path") != expected_path:
                errors.append(f"{method}/{key}: path must be {expected_path!r}")
            for field in ("db_version", "trained", "package_min", "files", "metrics"):
                if field not in entry:
                    errors.append(f"{method}/{key}: missing field {field!r}")
            expected_files = METHOD_FILES.get(method, set())
            for name in expected_files:
                if name not in entry.get("files", {}):
                    errors.append(f"{method}/{key}: missing file entry {name!r}")
            for name, finfo in entry.get("files", {}).items():
                if "sha256" not in finfo or "size" not in finfo:
                    errors.append(f"{method}/{key}/{name}: must have sha256 and size")

    for dbv, pentry in manifest.get("provenance", {}).items():
        expected_path = f"provenance/{dbv}"
        if pentry.get("path") != expected_path:
            errors.append(f"provenance/{dbv}: path must be {expected_path!r}")
        for name in PROVENANCE_FILES:
            if name not in pentry.get("files", {}):
                errors.append(f"provenance/{dbv}: missing file {name!r}")

    if errors:
        raise ValueError("Manifest validation failed:\n" + "\n".join(f"  - {e}" for e in errors))


