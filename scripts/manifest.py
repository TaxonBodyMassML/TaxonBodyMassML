def render_model_card(manifest: dict[str, Any]) -> str:
    """Render a Markdown model card suitable for the Hugging Face README."""
    lines = [
        "---",
        "license: other",
        'license_name: "MIT (model weights), CC BY-NC 4.0 (training data)"',
        "license_link: https://github.com/TaxonBodyMassML/TaxonBodyMassML/blob/main/LICENSE",
        "---",
        "",
        "# TaxonBodyMassML — Pre-trained body-mass prediction models",
        "",
        "Pre-trained models for predicting the body mass of animal taxa from "
        "their taxonomic classification (kingdom → genus).  "
        "Served by the [TaxonBodyMassML](https://github.com/TaxonBodyMassML/TaxonBodyMassML) "
        "R and Python packages.",
        "",
        f"**Artifact release:** `artifacts-{manifest.get('release', '?')}`",
        "",
        "## Model versions",
        "",
    ]

    for method, versions in sorted(manifest.get("models", {}).items()):
        lines.append(f"### {method}")
        lines.append("")
        header = (
            "| Version | DB version | Trained | R² | MAE (log₁₀ g)"
            " | Train n | Test n | Package min |"
        )
        lines.append(header)
        lines.append("|---|---|---|---|---|---|---|---|")
        for key in sorted(versions, key=lambda k: int(k[1:])):
            e = versions[key]
            m = e.get("metrics", {})
            r2 = f"{m.get('r2', 0):.3f}" if "r2" in m else "—"
            mae = f"{m.get('mae', 0):.3f}" if "mae" in m else "—"
            n_train = m.get("n_train", "—")
            n_test = m.get("n_test", "—")
            db_ver = e.get("db_version", "?")
            trained = e.get("trained", "?")[:10]
            pkg_min = e.get("package_min", "?")
            lines.append(
                f"| {key} | {db_ver} | {trained} | {r2} | {mae}"
                f" | {n_train} | {n_test} | ≥ {pkg_min} |"
            )
        if versions:
            last_key = sorted(versions, key=lambda k: int(k[1:]))[-1]
            total_size = sum(f["size"] for f in versions[last_key]["files"].values())
            lines.append(
                f"\n*Newest version ({last_key}) download size: " f"{total_size / 1e6:.0f} MB.*"
            )
        lines.append("")

    if manifest.get("provenance"):
        lines += [
            "## Provenance snapshots",
            "",
            "| DB version | Files |",
            "|---|---|",
        ]
        for dbv, pentry in sorted(manifest["provenance"].items()):
            fnames = ", ".join(f"`{n}`" for n in sorted(pentry.get("files", {})))
            lines.append(f"| {dbv} | {fnames} |")
        lines.append("")

    lines += [
        "## Usage",
        "",
        "```python",
        "# Python",
        "from taxonbodymassml import predict_mass, list_models",
        "print(list_models())                             # show all versions",
        'predict_mass("Nucella lima")                     # newest (default)',
        'predict_mass("Nucella lima", method_version=1)   # specific version',
        'predict_mass("Nucella lima", method_version="cached")  # keep using what you have',
        "```",
        "",
        "```r",
        "# R",
        "library(TaxonBodyMassML)",
        "list_models()                                    # show all versions",
        'predict_mass("Nucella lima")                     # newest (default)',
        'predict_mass("Nucella lima", method_version = 1) # specific version',
        'predict_mass("Nucella lima", method_version = "cached")  # keep local',
        "```",
        "",
        "See the package README for full documentation.",
    ]

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Utility
# ---------------------------------------------------------------------------


def sha256_file(path: str | Path) -> str:
    """Return the lowercase hex SHA-256 digest of the file at *path*."""
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()
